//! Contract generator: `typify` over the agent JSON Schemas of `packages/contracts/json-schema/` (AGS-03).
//!
//! `generate` returns the source of `adapters/src/contracts/generated.rs`. The committed file must equal that output;
//! `tests/contracts_are_current.rs` fails when they differ. Run `cargo run -p xtask -- contracts` to regenerate.

use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};

use syn::{Fields, Item, parse_quote};
use typify::{TypeSpace, TypeSpaceSettings};

pub mod character_fixture;
pub mod fixture;
pub mod fullscreen_fixture;

/// Each agent schema file and the Rust type it generates. The directory must hold exactly these files.
pub const CONTRACTS: &[(&str, &str)] = &[
    ("pairing-code.json", "PairingCodeResponse"),
    ("claim-request.json", "ClaimRequest"),
    ("claim.json", "ClaimResponse"),
    ("heartbeat.json", "Heartbeat"),
    ("assignment.json", "Assignment"),
    ("observation.json", "Observation"),
    (
        "agent-event-ready-check-resolved.json",
        "ReadyCheckResolvedEvent",
    ),
    (
        "agent-event-ready-check-started.json",
        "ReadyCheckStartedEvent",
    ),
    ("agent-event-room-assigned.json", "RoomAssignedEvent"),
    ("agent-event-room-run-opened.json", "RoomRunOpenedEvent"),
    ("record-characters-request.json", "RecordCharactersRequest"),
];

/// Fields holding a claim secret or the token. The generator types them as `d2rmm_agent_core::secret::Secret` (AGS-09).
pub const SECRET_FIELDS: &[(&str, &str)] = &[
    ("PairingCodeResponse", "claim_secret"),
    ("ClaimRequest", "claim_secret"),
    ("ClaimResponse", "token"),
];

/// The repository root, from this crate's manifest directory (`apps/agent/src-tauri/xtask`).
pub fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../..")
}

/// The directory holding the agent JSON Schemas written by `packages/contracts`.
pub fn schema_dir() -> PathBuf {
    repo_root().join("packages/contracts/json-schema")
}

/// The committed generator output in the adapters crate.
pub fn generated_path() -> PathBuf {
    repo_root().join("apps/agent/src-tauri/adapters/src/contracts/generated.rs")
}

/// The committed copy of the agent schemas in the adapters crate. Its schema tests read the copy, so they also run from a
/// copy of the crate (cargo-mutants), where `packages/contracts` is out of reach.
pub fn schema_module_path() -> PathBuf {
    repo_root().join("apps/agent/src-tauri/adapters/src/contracts/schemas.rs")
}

/// The source of the schema module: each agent schema as a string, byte for byte, in `SCHEMAS`. Rust holds the text, so
/// the prettier sensor, which skips the generated `packages/contracts/json-schema`, never reformats the copy.
pub fn generate_schema_module(schema_dir: &Path) -> Result<String, Box<dyn Error>> {
    let mut module = String::from(
        "// Generated by `cargo run -p xtask -- contracts` from packages/contracts/json-schema. Do not edit.\n\
         //! The agent JSON Schemas as the API publishes them, for the adapters' schema tests.\n\
         #![cfg_attr(rustfmt, rustfmt_skip)]\n\n\
         /// Each agent schema file and its text.\n\
         pub const SCHEMAS: &[(&str, &str)] = &[\n",
    );
    for (file, _) in CONTRACTS {
        let text = fs::read_to_string(schema_dir.join(file))?;
        if text.contains("\"##") {
            return Err(format!("{file} holds the raw string delimiter `\"##`").into());
        }
        module.push_str(&format!("    (\"{file}\", r##\"{text}\"##),\n"));
    }
    module.push_str("];\n");
    Ok(module)
}

/// Generates the Rust source of the contract types from the schemas in `schema_dir`.
pub fn generate(schema_dir: &Path) -> Result<String, Box<dyn Error>> {
    let mut expected: Vec<String> = CONTRACTS.iter().map(|(file, _)| file.to_string()).collect();
    expected.sort();
    if schema_file_names(schema_dir)? != expected {
        return Err(format!(
            "{} must hold exactly the files of CONTRACTS",
            schema_dir.display()
        )
        .into());
    }

    let mut space = TypeSpace::new(&TypeSpaceSettings::default());
    for (file, type_name) in CONTRACTS {
        let text = fs::read_to_string(schema_dir.join(file))?;
        let mut schema: serde_json::Value = serde_json::from_str(&text)?;
        let object = schema
            .as_object_mut()
            .ok_or_else(|| format!("{file} is not a JSON object"))?;
        // The root title names the generated type; the schema files stay as the API publishes them.
        object.insert("title".to_string(), serde_json::Value::from(*type_name));
        let root: schemars::schema::RootSchema = serde_json::from_value(schema)?;
        space.add_root_schema(root)?;
    }

    let mut file: syn::File = syn::parse2(space.to_stream())?;
    for (struct_name, field_name) in SECRET_FIELDS {
        retype_secret_field(&mut file, struct_name, field_name)?;
    }
    file.attrs
        .push(parse_quote!(#![allow(clippy::all, clippy::pedantic)]));
    // Generated code keeps typify's layout; rustfmt must not rewrap it, so `cargo fmt --check` stays green.
    file.attrs
        .push(parse_quote!(#![cfg_attr(rustfmt, rustfmt_skip)]));

    Ok(format!(
        "// Generated by `cargo run -p xtask -- contracts` from packages/contracts/json-schema. Do not edit.\n{}",
        prettyplease::unparse(&file)
    ))
}

/// Points a generated field at `Secret` and serializes it only through `secret::expose`.
fn retype_secret_field(
    file: &mut syn::File,
    struct_name: &str,
    field_name: &str,
) -> Result<(), Box<dyn Error>> {
    let fields = file
        .items
        .iter_mut()
        .find_map(|item| match item {
            Item::Struct(item) if item.ident == struct_name => Some(&mut item.fields),
            _ => None,
        })
        .ok_or_else(|| format!("generated struct {struct_name} not found"))?;
    let Fields::Named(named) = fields else {
        return Err(format!("{struct_name} has no named fields").into());
    };
    let field = named
        .named
        .iter_mut()
        .find(|field| {
            field
                .ident
                .as_ref()
                .is_some_and(|ident| ident == field_name)
        })
        .ok_or_else(|| format!("field {struct_name}.{field_name} not found"))?;
    field.ty = parse_quote!(d2rmm_agent_core::secret::Secret);
    field
        .attrs
        .push(parse_quote!(#[serde(serialize_with = "d2rmm_agent_core::secret::expose")]));
    Ok(())
}

/// Names of the schema files in `schema_dir`, sorted. Used to keep `CONTRACTS` exhaustive.
pub fn schema_file_names(schema_dir: &Path) -> Result<Vec<String>, Box<dyn Error>> {
    let mut names = Vec::new();
    for entry in fs::read_dir(schema_dir)? {
        let name = entry?.file_name().to_string_lossy().into_owned();
        if name.ends_with(".json") {
            names.push(name);
        }
    }
    names.sort();
    Ok(names)
}
